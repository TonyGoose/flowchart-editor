let _layoutedVariants = null;
const getLayoutedDefaults = () => {
  if (!_layoutedVariants) {
    _layoutedVariants = Object.fromEntries(
      Object.entries(VARIANTS).map(([id, v]) => [id, autoLayoutVariant(v)])
    );
  }
  return _layoutedVariants;
};

export const loadVariants = () => {
  const saved = localStorage.getItem('variants');
  return saved ? JSON.parse(saved) : getLayoutedDefaults();
};

export const saveVariants = (variants) => {
  localStorage.setItem('variants', JSON.stringify(variants));
};

